"""Turn Adobe's CMap text files into one compressed blob compiled into the engine.

    python3 scripts/build-cmaps.py <cmap-resources checkout> > src/cpp/cmaps_data.cpp

Adobe ships these as PostScript-ish CMaps (BSD-3-Clause, see THIRD-PARTY.md). A
viewer needs the codespace ranges (how many bytes a code occupies) and the code
-> CID mapping; the rest of the CMap (glyph names, usecmap plumbing) is not.

The blob is zlib-compressed at build time and inflated once at runtime, which
takes 179 CMaps from 5.2 MB to ~1 MB. Format (varints little endian, 7 bits per
byte):

    "WCM2" <nTables>
    per table: <nameLen> name <nRanges> [<nbytes><lo><hi>]... <nPairs>
               per pair: <deltaCode> <zigzag(deltaCid)>
"""
import pathlib
import re
import sys
import zlib

FAMILIES = ["Adobe-Japan1-7", "Adobe-GB1-6", "Adobe-CNS1-7", "Adobe-Korea1-2", "Adobe-KR-9"]


def parse(path):
    text = path.read_text("latin-1")
    ranges, pairs = [], []
    for block in re.findall(r"begincodespacerange(.*?)endcodespacerange", text, re.S):
        for lo, hi in re.findall(r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>", block):
            if len(lo) == len(hi):
                ranges.append((len(lo) // 2, int(lo, 16), int(hi, 16)))
    for block in re.findall(r"begincidrange(.*?)endcidrange", text, re.S):
        for lo, hi, cid in re.findall(r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*(\d+)", block):
            if len(lo) != len(hi):
                continue
            start, end, base = int(lo, 16), int(hi, 16), int(cid)
            for code in range(start, end + 1):
                pairs.append((len(lo) // 2, code, base + code - start))
    for block in re.findall(r"begincidchar(.*?)endcidchar", text, re.S):
        for code, cid in re.findall(r"<([0-9A-Fa-f]+)>\s*(\d+)", block):
            pairs.append((len(code) // 2, int(code, 16), int(cid)))
    pairs.sort()
    return ranges, pairs


def varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def zig(n):
    return (n << 1) if n >= 0 else ((-n << 1) - 1)


def main():
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/cmapsrc")
    tables = []
    for family in FAMILIES:
        cmap_dir = root / family / "CMap"
        if not cmap_dir.is_dir():
            continue
        for path in sorted(cmap_dir.iterdir()):
            if path.is_dir() or path.suffix == ".txt":
                continue
            ranges, pairs = parse(path)
            if pairs:
                tables.append((path.name, ranges, pairs))

    blob = bytearray(b"WCM2")
    blob += varint(len(tables))
    for name, ranges, pairs in tables:
        raw = name.encode()
        blob += varint(len(raw)) + raw + varint(len(ranges))
        for nbytes, lo, hi in ranges:
            blob += bytes([nbytes]) + varint(lo) + varint(hi)
        blob += varint(len(pairs))
        prev_n = prev_code = prev_cid = 0
        for nbytes, code, cid in pairs:
            key = (nbytes << 32) | code
            prev_key = (prev_n << 32) | prev_code
            blob += varint(key - prev_key)
            blob += varint(zig(cid - prev_cid))
            prev_n, prev_code, prev_cid = nbytes, code, cid

    packed = zlib.compress(bytes(blob), 9)
    sys.stderr.write(
        f"{len(tables)} CMaps, {sum(len(p) for _, _, p in tables)} mappings, "
        f"{len(blob) // 1024} KB raw, {len(packed) // 1024} KB compressed\n"
    )

    out = sys.stdout
    out.write("// Generated by scripts/build-cmaps.py - do not edit.\n")
    out.write("// Adobe CMap resources, BSD-3-Clause (see THIRD-PARTY.md).\n")
    out.write("#include <cstddef>\n\n")
    out.write("namespace pdf {\nnamespace cmapdata {\n")
    out.write(f"extern const size_t kRawSize = {len(blob)};\n")
    out.write("extern const unsigned char kPacked[] = {\n")
    for i in range(0, len(packed), 16):
        out.write("  " + ", ".join(str(b) for b in packed[i:i + 16]) + ",\n")
    out.write("};\n")
    out.write(f"extern const size_t kPackedSize = {len(packed)};\n")
    out.write("}  // namespace cmapdata\n}  // namespace pdf\n")


if __name__ == "__main__":
    main()
