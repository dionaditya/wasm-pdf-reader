#!/usr/bin/env python3
"""Calibrate device CMYK -> sRGB against the reference renderer.

DeviceCMYK carries no profile, so every renderer picks a default. Ours used
(1-c)(1-k), which is far too saturated — a 20/80/0/0 patch came out royal blue
where MuPDF shows a violet. Rather than guess at a formula, sample a 9^4 grid of
CMYK patches through MuPDF once and embed the result as a LUT. The header this
writes is compiled into the engine; cmykToRgb() interpolates it.
"""
import os

import numpy as np
import pymupdf

N = 9                    # samples per axis (0, 1/8 .. 1)
CELL = 10                # points per patch
SIDE = N * N             # 81 patches per row/column -> N^4 = 6561 cells
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "src", "cpp", "cmyk_lut.h")

doc = pymupdf.open()
page_w = SIDE * CELL
page = doc.new_page(width=page_w, height=page_w)

for idx in range(N ** 4):
    c = (idx % N) / (N - 1)
    m = ((idx // N) % N) / (N - 1)
    y = ((idx // (N * N)) % N) / (N - 1)
    k = ((idx // (N ** 3)) % N) / (N - 1)
    col = idx % SIDE
    row = idx // SIDE
    x0, y0 = col * CELL, row * CELL
    page.draw_rect(pymupdf.Rect(x0, y0, x0 + CELL, y0 + CELL),
                   color=None, fill=(c, m, y, k), fill_opacity=1)

pix = page.get_pixmap(matrix=pymupdf.Matrix(1, 1), alpha=False)
arr = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, 3)

lut = np.zeros((N ** 4, 3), dtype=np.uint8)
for idx in range(N ** 4):
    col = idx % SIDE
    row = idx // SIDE
    # centre of the patch, 1px inside the border where antialiasing lives
    x = col * CELL + CELL // 2
    y = row * CELL + CELL // 2
    lut[idx] = arr[y, x]

doc.close()

with open(OUT_H, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/make_cmyk_lut.py — device CMYK sampled through\n")
    f.write("// the reference renderer on a 9^4 grid, interpolation order own_c, m, y, k.\n")
    f.write("// Do not edit by hand; re-run the script instead.\n")
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write("namespace pdf {\n")
    f.write("static const int kCmykLutN = %d;\n" % N)
    f.write("static const unsigned char kCmykLut[%d][3] = {\n" % (N ** 4))
    for i in range(N ** 4):
        r, g, b = (int(v) for v in lut[i])
        f.write("  {%3d,%3d,%3d},\n" % (r, g, b))
    f.write("};\n}  // namespace pdf\n")

print("wrote", OUT_H, "with", N ** 4, "entries")
print("sanity: 0,0,0,0 ->", lut[0], " 1,1,1,1 ->", lut[-1])
