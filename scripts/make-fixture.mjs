#!/usr/bin/env node
// make-fixture.mjs — write the PDF used by the demo page and the tests.
//
// It is generated (not committed as an opaque binary) so the repository owns
// its test asset outright: three pages, standard-14 text, vector fills and
// strokes, an embedded RGB image, a rotated landscape page and a document info
// dictionary. Run `node scripts/make-fixture.mjs` to regenerate.
//
// Output: test/fixtures/reader-sample.pdf

import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, '..', 'test', 'fixtures', 'reader-sample.pdf');

const W = 612;
const H = 792;

const esc = (s) => s.replace(/([\\()])/g, '\\$1');

function text(font, size, x, y, str, { color } = {}) {
  const fill = color ? `${color[0]} ${color[1]} ${color[2]} rg\n` : '';
  return `${fill}BT /${font} ${size} Tf ${x} ${y} Td (${esc(str)}) Tj ET\n`;
}

// ── page 1: type specimen ────────────────────────────────────────────────────
function page1() {
  let c = '';
  // header band
  c += '0.10 0.16 0.28 rg 0 712 612 80 re f\n';
  c += '0.35 0.55 0.95 rg 0 706 612 6 re f\n';
  c += text('F2', 26, 44, 748, 'WASM PDF READER', { color: [1, 1, 1] });
  c += text('F1', 11, 44, 726, 'a PDF parser and rasterizer compiled to WebAssembly', { color: [0.78, 0.84, 0.95] });

  // title + rule
  c += text('F2', 20, 44, 650, 'One file, three pages, no server', { color: [0.1, 0.16, 0.28] });
  c += '0.75 0.78 0.82 RG 2 w 44 634 m 568 634 l S\n';

  // paragraphs
  const body = [
    'Everything on this page was drawn by the bundled C++ reader: the text is',
    'positioned with the standard-14 Helvetica metrics, the rules and the boxes',
    'are vector paths, and the page is rasterized to RGBA in WebAssembly.',
    '',
    'The same module exposes a text layer, so a viewer built on this library can',
    'select, copy and search without a second parser.',
  ];
  let y = 604;
  for (const line of body) {
    if (line) c += text('F1', 12, 44, y, line, { color: [0.15, 0.16, 0.18] });
    y -= 19;
  }

  // three colour swatches with labels
  const swatches = [
    ['0.20 0.45 0.90', 'accent'],
    ['0.16 0.62 0.45', 'success'],
    ['0.90 0.42 0.20', 'warning'],
  ];
  swatches.forEach(([rgb, label], i) => {
    const x = 44 + i * 120;
    c += `${rgb} rg ${x} 430 96 64 re f\n`;
    c += text('F1', 10, x, 416, label, { color: [0.35, 0.36, 0.4] });
  });

  // a stroked rounded shape via beziers + dashes
  c += '0.2 0.3 0.7 RG 2.5 w [6 4] 0 d 44 372 m 44 320 l 552 320 l 552 372 l 44 372 l S\n';
  c += text('F1', 12, 60, 340, 'dashed stroke, round joins, one path operator chain', { color: [0.2, 0.3, 0.7] });

  // filled circle-ish (four beziers)
  const k = 0.5523;
  c += '0.93 0.94 0.98 rg 0.2 0.3 0.7 RG 1 w [0 0] 0 d ';
  c += '306 230 m 306 264 334 292 368 292 c 402 292 430 264 430 230 c 430 196 402 168 368 168 c 334 168 306 196 306 230 c B\n';

  // text inside the circle, centred by hand
  c += text('F2', 16, 344, 235, 'wasm', { color: [0.12, 0.2, 0.4] });
  c += text('F1', 9, 330, 218, '3-page sample', { color: [0.35, 0.36, 0.4] });

  // footer
  c += text('F1', 9, 44, 40, 'page 1 of 3 — generated by scripts/make-fixture.mjs', { color: [0.55, 0.56, 0.6] });
  return c;
}

// ── page 2: image + grid ────────────────────────────────────────────────────
function page2() {
  let c = '';
  c += text('F2', 18, 44, 720, 'Images and clipping', { color: [0.1, 0.16, 0.28] });
  c += text('F1', 12, 44, 696, 'The 48 × 48 checker below is an /Image XObject with a FlateDecode stream.', { color: [0.2, 0.2, 0.24] });

  // image placement
  c += 'q 48 0 0 48 44 620 cm /Im1 Do Q\n';

  // uniform grid drawn with one path per cell
  let x = 44;
  let y = 560;
  c += '0.85 0.87 0.92 RG 0.8 w\n';
  for (let col = 0; col < 6; col++) {
    for (let row = 0; row < 4; row++) {
      c += `${x + col * 84} ${y - row * 34} 84 34 re S\n`;
    }
  }
  for (let col = 0; col < 6; col++) {
    for (let row = 0; row < 4; row++) {
      c += text('F1', 9, x + col * 84 + 6, y - row * 34 + 12, `${col},${row}`, { color: [0.35, 0.38, 0.45] });
    }
  }

  // clipped fill
  c += 'q 44 240 240 160 re W n 0.95 0.55 0.2 rg 44 240 520 160 re f Q\n';
  c += text('F1', 11, 54, 260, 'this orange band is clipped to the rectangle on the left', { color: [0.3, 0.18, 0.05] });

  // small type block
  const lines = [
    'Clipping is applied with the W n operator pair, exactly as a print',
    'engine would: the fill below it is much wider than the visible area.',
    'Text comes from glyph runs the reader reports in page space, which is',
    'what a selection or search layer consumes.',
  ];
  let ty = 200;
  for (const line of lines) {
    c += text('F1', 11, 44, ty, line, { color: [0.15, 0.16, 0.18] });
    ty -= 17;
  }

  c += text('F1', 9, 44, 40, 'page 2 of 3', { color: [0.55, 0.56, 0.6] });
  return c;
}

// ── page 3: rotated landscape ───────────────────────────────────────────────
function page3() {
  // Authored in the page's own 612 x 792 space; the /Rotate entry turns it into
  // a 792 x 612 landscape view. Everything stays inside the media box, so the
  // rotation is the only difference from the other pages.
  let c = '';
  c += text('F2', 22, 44, 720, 'Landscape, /Rotate 90', { color: [0.1, 0.16, 0.28] });
  c += text('F1', 12, 44, 694, 'The media box is 612 x 792 with a /Rotate 90 entry, so the', { color: [0.2, 0.2, 0.24] });
  c += text('F1', 12, 44, 676, 'displayed page is 792 x 612 and the content is turned.', { color: [0.2, 0.2, 0.24] });

  // bars, painted from the left edge
  const bars = [0.15, 0.3, 0.45, 0.6, 0.75];
  bars.forEach((v, i) => {
    c += `0.25 ${0.35 + i * 0.11} 0.85 rg 44 ${326 + i * 50} 300 36 re f\n`;
    void v;
  });
  c += text('F1', 10, 44, 310, 'vector bars', { color: [0.4, 0.42, 0.48] });

  // big word: after the rotation it reads down the page
  c += text('F2', 56, 44, 150, 'ROTATED', { color: [0.12, 0.2, 0.4] });
  c += text('F1', 11, 44, 130, 'the same glyphs, rotated with the page', { color: [0.4, 0.42, 0.48] });

  c += text('F1', 9, 44, 40, 'page 3 of 3', { color: [0.55, 0.56, 0.6] });
  return c;
}

// ── image: 48x48 RGB checker with a gradient ───────────────────────────────
function imageData() {
  const w = 48;
  const h = 48;
  const buf = Buffer.alloc(w * h * 3);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const checker = ((x >> 3) + (y >> 3)) % 2 === 0;
      const i = (y * w + x) * 3;
      const g = Math.round(60 + (x / w) * 150);
      buf[i] = checker ? 30 : g;
      buf[i + 1] = checker ? 120 : Math.round(40 + (y / h) * 140);
      buf[i + 2] = checker ? 210 : 90;
    }
  }
  return { w, h, buf };
}

// ── assemble the file ───────────────────────────────────────────────────────
const img = imageData();
const stream = (content) => deflateSync(Buffer.from(content, 'latin1'));

const objects = [];
const add = (body) => { objects.push(body); return objects.length; }; // 1-based

const catalogNum = add(null);   // filled in later
const pagesNum = add(null);
const pageNums = [0, 0, 0];

const fontHelvetica = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
const fontBold = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');

const imgStream = deflateSync(img.buf);
const imageNum = add({
  dict: `<< /Type /XObject /Subtype /Image /Width ${img.w} /Height ${img.h} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /FlateDecode /Length ${imgStream.length} >>`,
  stream: imgStream,
});

function contentObject(content) {
  const data = stream(content);
  return add({
    dict: `<< /Length ${data.length} /Filter /FlateDecode >>`,
    stream: data,
  });
}

const c1 = contentObject(page1());
const c2 = contentObject(page2());
const c3 = contentObject(page3());

const infoNum = add('<< /Title (WASM PDF Reader sample) /Author (wasm-pdf-reader) /Subject (Generated test document) /Creator (scripts/make-fixture.mjs) /Producer (wasm-pdf-reader) /CreationDate (D:20260101000000Z) >>');

const resources = `<< /Font << /F1 ${fontHelvetica} 0 R /F2 ${fontBold} 0 R >> /XObject << /Im1 ${imageNum} 0 R >> >>`;
const resourcesPlain = `<< /Font << /F1 ${fontHelvetica} 0 R /F2 ${fontBold} 0 R >> >>`;

pageNums[0] = add(`<< /Type /Page /Parent ${pagesNum} 0 R /MediaBox [0 0 ${W} ${H}] /Resources ${resourcesPlain} /Contents ${c1} 0 R >>`);
pageNums[1] = add(`<< /Type /Page /Parent ${pagesNum} 0 R /MediaBox [0 0 ${W} ${H}] /Resources ${resources} /Contents ${c2} 0 R >>`);
pageNums[2] = add(`<< /Type /Page /Parent ${pagesNum} 0 R /MediaBox [0 0 ${W} ${H}] /Rotate 90 /Resources ${resourcesPlain} /Contents ${c3} 0 R >>`);

objects[pagesNum - 1] = `<< /Type /Pages /Kids [${pageNums.map((n) => `${n} 0 R`).join(' ')}] /Count 3 >>`;
objects[catalogNum - 1] = `<< /Type /Catalog /Pages ${pagesNum} 0 R >>`;

// serialise with a classic xref table
let pdf = '%PDF-1.7\n%\xE2\xE3\xCF\xD3\n';
const offsets = [0];
objects.forEach((obj, i) => {
  offsets[i + 1] = Buffer.byteLength(pdf, 'latin1');
  if (typeof obj === 'string') {
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  } else {
    pdf += `${i + 1} 0 obj\n${obj.dict}\nstream\n`;
    pdf += obj.stream.toString('latin1');
    pdf += '\nendstream\nendobj\n';
  }
});

const xrefStart = Buffer.byteLength(pdf, 'latin1');
pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
for (let i = 1; i <= objects.length; i++) {
  pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
}
pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogNum} 0 R /Info ${infoNum} 0 R >>\n`;
pdf += `startxref\n${xrefStart}\n%%EOF\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, Buffer.from(pdf, 'latin1'));

// Expectations the tests assert on; kept next to the fixture so they cannot drift.
const expectations = {
  pages: 3,
  title: 'WASM PDF Reader',
  pageSize: [[W, H, 0], [W, H, 0], [H, W, 90]],   // [width, height, rotation]
  page2Text: 'Images and clipping',
  pageText: {
    0: ['WASM PDF READER', 'One file, three pages, no server', 'wasm'],
    1: ['Images and clipping', 'Clipping is applied with the W n operator pair'],
    2: ['Landscape, /Rotate 90', 'ROTATED'],
  },
  metadata: { Title: 'WASM PDF Reader sample', Author: 'wasm-pdf-reader' },
};
writeFileSync(join(dirname(outFile), 'reader-sample.json'), `${JSON.stringify(expectations, null, 2)}\n`);

console.log(`wrote ${outFile} (${pdf.length} bytes)`);
